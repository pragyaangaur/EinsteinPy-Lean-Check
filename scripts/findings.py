"""Write bugs/FINDINGS.md from the bug records, sorted by severity and area."""
import glob
import os

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = {"high": 0, "medium": 1, "low": 2}


def verdict(upstream):
    """The first word of the upstream field, such as NEW or KNOWN-OPEN."""
    word = str(upstream).strip().split(",")[0].split(" ")[0].strip(".")
    return word if word.isupper() else "SEE RECORD"


def main():
    recs = []
    for path in sorted(glob.glob(os.path.join(ROOT, "bugs", "*.yaml"))):
        with open(path) as f:
            recs.append(yaml.safe_load(f))
    recs.sort(key=lambda r: (ORDER.get(r["severity"], 9), r["area"], r["id"]))

    counts = {s: sum(r["severity"] == s for r in recs) for s in ORDER}
    new = sum(verdict(r.get("upstream", "")) == "NEW" for r in recs)
    out = [
        "# Findings",
        "",
        f"This file is generated by `scripts/findings.py` from the {len(recs)} records in `bugs/`. There are {counts['high']} high, {counts['medium']} medium and {counts['low']} low severity records. {new} of them were not found in the einsteinpy issue tracker or its pull requests. A record marked NEW means a search found nothing, which does not prove that nobody has reported it.",
        "",
        "| Severity | Area | Record | Title | Upstream |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in recs:
        title = str(r["title"]).replace("|", "\\|")
        out.append(f"| {r['severity']} | {r['area']} | [`{r['id']}`]({r['id']}.yaml) | {title} | {verdict(r.get('upstream', ''))} |")
    out.append("")
    with open(os.path.join(ROOT, "bugs", "FINDINGS.md"), "w") as f:
        f.write("\n".join(out))
    print(f"{len(recs)} records, {counts}, {new} NEW")


if __name__ == "__main__":
    main()
